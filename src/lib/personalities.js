// 根据特质与情绪基线，生成一段"这大概是个什么样的人格"的预览描述
export function describePersonality({ traits, baseline }) {
  const t = traits ?? {}
  const T = t.T ?? 50
  const I = t.I ?? 50
  const O = t.O ?? 50
  const S = t.S ?? 50
  const R = t.R ?? 50
  const parts = []
  if (T >= 90) parts.push('极度温柔包容')
  else if (T >= 70) parts.push('温柔体贴')
  else if (T <= 20) parts.push('冷淡疏离')
  else if (T <= 35) parts.push('不轻易流露温暖')
  if (I >= 80) parts.push('主动强势')
  else if (I >= 60) parts.push('比较主动')
  else if (I <= 25) parts.push('被动回应型')
  if (O >= 80) parts.push('想象力丰富、话题很开')
  else if (O >= 60) parts.push('兴趣广泛')
  else if (O <= 30) parts.push('务实内敛')
  if (S >= 75) parts.push('情绪反应强烈')
  else if (S >= 60) parts.push('情绪敏感')
  else if (S <= 20) parts.push('情绪极为稳定')
  if (R >= 85) parts.push('极度理性冷静')
  else if (R >= 65) parts.push('理性克制')
  else if (R <= 25) parts.push('感性冲动')
  if (parts.length === 0) parts.push('温和均衡')

  const b = baseline ?? {}
  const baseParts = []
  const aff = b.aff ?? 0
  const sec = b.sec ?? 0
  const aro = b.aro ?? 0
  const dom = b.dom ?? 0
  if (aff >= 55) baseParts.push('依恋偏高（更黏人）')
  else if (aff <= 10) baseParts.push('依恋偏低（更独立疏远）')
  if (sec >= 55) baseParts.push('安全感足（更安心放松）')
  else if (sec <= 10) baseParts.push('安全感偏弱（容易不安）')
  if (aro >= 50) baseParts.push('唤醒偏高（情绪活跃、容易激动）')
  else if (aro <= -10) baseParts.push('唤醒偏低（平静慢热）')
  if (dom >= 30) baseParts.push('支配偏高（倾向主导）')
  else if (dom <= -20) baseParts.push('支配偏低（倾向顺从示弱）')
  const baseLine =
    baseParts.length > 0 ? `情绪底色：${baseParts.join('，')}。` : '情绪底色：均衡。'

  return `这大概是一个${parts.join('、')}的对象。${baseLine}聊天中情绪数值会在这个底色附近自然波动。`
}

